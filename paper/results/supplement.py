"""Generate the main-body benchmark audit from unrounded seed means.

No simulation or policy evaluation. Paired effects are formed within market and
master seed before applying the publication's 10,000-resample bootstrap.
"""
from pathlib import Path
import hashlib
import json
import numpy as np
import pandas as pd
from lmm.experiments.make_report import mean_interval

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
REPORT = REPO / 'results/revision_v20/_publication'
SOURCE = REPORT / 'audit/economic_by_seed.csv'
MARKETS = ('Synthetic', 'CAT', 'GOOGL', 'JPM', 'MSFT', 'PG')
LEARNERS = ('dqn', 'ddpg', 'td3', 'sac')


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def generate():
    publication = json.loads((REPORT / 'manifest.json').read_text())
    assert sha(SOURCE) == publication['outputs']['audit/economic_by_seed.csv']
    data = pd.read_csv(SOURCE)
    assert len(data) == 360 and data.n_episodes.eq(100).all()
    assert not data.duplicated(['market', 'policy', 'seed']).any()
    rows = []
    for market in MARKETS:
        frame = data[data.market == market]
        objective = frame.pivot(index='seed', columns='policy', values='objective_bps')
        assert objective.shape == (10, 6) and np.isfinite(objective).all().all()
        for policy in (*LEARNERS, 'as'):
            group = frame[frame.policy == policy].set_index('seed').sort_index()
            # Reverse the score interval to preserve the publication's exact
            # bootstrap convention under the shortfall sign transformation.
            mean, lo, hi = mean_interval(group.pnl_bps)
            row = dict(market=market, policy=policy, n_seeds=10,
                       ordinary_mean=-mean, ordinary_ci_low=-hi, ordinary_ci_high=-lo)
            if policy in LEARNERS:
                for reference in ('as', 'twap'):
                    paired = objective[policy] - objective[reference]
                    assert np.allclose(paired, group[f'gap_{reference}_bps'], rtol=0, atol=1e-10)
                    mean, lo, hi = mean_interval(paired)
                    row.update({f'{reference}_mean': mean, f'{reference}_ci_low': lo,
                                f'{reference}_ci_high': hi})
            rows.append(row)
    summary = pd.DataFrame(rows)
    csv = HERE / 'benchmark_supplement.csv'
    summary.to_csv(csv, index=False)
    tex = HERE / 'benchmark_supplement.tex'
    lines = [r'% Generated by paper/results/supplement.py; edit the generator.',
             r'\begin{table}[!htbp]', r'\centering\small',
             r'\setlength{\tabcolsep}{5pt}', r'\renewcommand{\arraystretch}{1.08}',
             r'\begin{tabular}{@{}llrrr@{}}', r'\toprule',
             r'\textbf{Market} & \textbf{Policy} & \textbf{Ordinary shortfall} & \multicolumn{2}{c}{\textbf{Paired penalized-shortfall reduction}} \\',
             r'\cmidrule(l){4-5}',
             r' & & $\mathrm{IS}$ [95\% CI] & versus AS [95\% CI] & versus TWAP [95\% CI] \\',
             r'\midrule']
    def cell(row, prefix):
        return f'${row[prefix+"_mean"]:.2f}\\;[{row[prefix+"_ci_low"]:.2f},{row[prefix+"_ci_high"]:.2f}]$'
    for i, market in enumerate(MARKETS):
        if i:
            lines.append(r'\addlinespace[5pt]')
        for j, row in enumerate(r for r in rows if r['market'] == market):
            paired = [cell(row, ref) for ref in ('as', 'twap')] if row['policy'] in LEARNERS else ['---', '---']
            lines.append(' & '.join([market if j == 0 else '', row['policy'].upper(),
                                    cell(row, 'ordinary'), *paired]) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular}',
              r'\caption{Market-specific shortfalls in basis points. Ordinary shortfall reports policy levels; paired reductions equal reference-minus-learner penalized shortfall, so positive values favor the learner. Brackets give pointwise 95\% seed-bootstrap intervals, unadjusted for multiple comparisons.}',
              r'\label{tab:benchmark_supplement}', r'\end{table}', '']
    tex.write_text('\n'.join(lines))
    manifest = dict(campaign='revision_v20', rows=30, paired_comparisons=48,
                    ordinary_shortfall_levels=30, seeds_per_market=10, episodes_per_seed=100,
                    bootstrap='Publication mean_interval: 10000 resamples, RNG seed 0, sorted input values; reverse PnL interval endpoints for ordinary shortfall.',
                    inputs={str(p.relative_to(REPO)): sha(p) for p in (SOURCE, REPORT / 'manifest.json')},
                    outputs={str(p.relative_to(REPO)): sha(p) for p in (csv, tex)},
                    source_script_sha256=sha(Path(__file__)))
    (HERE / 'supplement_manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print('Generated benchmark table: 48 paired comparisons and 30 ordinary-shortfall levels.')


if __name__ == '__main__':
    generate()
